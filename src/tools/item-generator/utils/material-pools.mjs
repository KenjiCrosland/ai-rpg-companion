/**
 * Material pools per origin.
 *
 * Background: prior to this module the item generator rolled materials
 * from a single 20-entry pool, independent of origin. That produced two
 * recurring failure modes:
 *   1. Thematic mismatches (Elven origin + beetle chitin → "Númelen's
 *      Carapace," an elven armor of beetle shell that the LLM had to
 *      narratively rescue).
 *   2. Visible repetition (frozen flame, coral, cloud marble surfacing
 *      across many generations because every origin drew from the same
 *      small pool).
 *
 * The fix mirrors the mood-origin compatibility map already in place:
 * each origin gets a curated list of materials that fit its thematic
 * register, and selection picks from the origin's pool rather than the
 * union. Materials repeat less because per-origin pools are smaller and
 * more focused.
 *
 * Two-tier composition rule:
 *   - Aesthetic origins (Abyssal, Aberrant, Astral, Celestial, etc.)
 *     have narrower pools (~18-22 materials) tightly themed to the
 *     register. The aesthetic IS the material register, so straying
 *     hurts coherence.
 *   - Cultural origins (Orcish, Dwarven, Elven, Goblinoid, Gnomish,
 *     Giant) have broader pools (~35-40 materials) including refined,
 *     utilitarian, and cross-tradition items. Real cultures use the
 *     materials available in their environment plus what they acquire
 *     by trade or conquest; reducing them to single-aesthetic registers
 *     is the stereotyping the broader pool prevents.
 *
 * Format mirrors the legacy materials array — `'<name> — <sensory
 * description>'`. The descriptive tail gives the LLM concrete texture
 * to ground physical_description on rather than just a label.
 *
 * Materials may appear in multiple pools where the thematic association
 * is genuine (fossilized bone fits Necromantic, Primordial, Draconic;
 * include it in all three rather than gatekeeping). The Set-based union
 * in `allMaterials` deduplicates for the fallback case.
 */

